"""ASGI entry point: `uvicorn app.main:app --reload`."""

from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.responses import HTMLResponse

from app import storage
from app.routes import router
from app.middleware import RateLimitMiddleware


def _route_table(app: FastAPI) -> list[tuple[str, str]]:
    """(method, path) pairs for every registered route, in a stable order.

    Reads `app.openapi()["paths"]` rather than walking `app.routes`
    directly: FastAPI's internal representation of an included router's
    routes is not part of its stable public API and has changed shape
    between versions, while the OpenAPI schema -- the same one that drives
    the real `/docs` page -- is guaranteed to reflect everything actually
    registered. Shared by the startup log and the `/` landing page so the
    two can never drift apart.
    """
    paths = app.openapi()["paths"]
    return [
        (method, path)
        for path in sorted(paths)
        for method in sorted(m.upper() for m in paths[path] if m.upper() != "OPTIONS")
    ]


def _print_routes(app: FastAPI) -> None:
    """Most of this API isn't clickable in a browser -- POST/DELETE need a
    body, and GET routes with a {code} need one to already exist -- so
    printing the route table at startup is the difference between a
    developer finding it in this log and one giving up on a bare 404 at `/`.
    """
    # flush=True: stdout is fully (not line-) buffered whenever it isn't an
    # interactive terminal -- piped through `tee`, redirected to a log file,
    # captured by a process supervisor -- so without it this can sit in the
    # buffer indefinitely instead of showing up when it matters most.
    print("\nAvailable endpoints:", flush=True)
    for method, path in _route_table(app):
        print(f"  {method:<7} {path}", flush=True)
    print("  interactive docs: /docs\n", flush=True)


@asynccontextmanager
async def lifespan(app: FastAPI):
    storage.init_db()
    _print_routes(app)
    yield


app = FastAPI(title="URL Shortener", version="1.0", lifespan=lifespan)

app.add_middleware(RateLimitMiddleware)

# Registered before `router`: `/{code}` in routes.py is a catch-all for any
# single path segment, so a literal route added after it would never match --
# Starlette dispatches to the first route whose pattern matches, in
# registration order. `/` itself has no segment at all so it can't collide
# with `/{code}` either way, but it's kept here with `/health` for the same
# "the routes meant to be found directly are declared up front" reason.
@app.get("/health")
def health() -> dict:
    return {"status": "ok"}


@app.get("/", include_in_schema=False)
def home() -> HTMLResponse:
    rows = "\n".join(
        f"<tr><td>{method}</td><td><code>{path}</code></td></tr>"
        for method, path in _route_table(app)
    )
    html = f"""<!doctype html>
<html>
<head><title>URL Shortener</title></head>
<body style="font-family: system-ui, sans-serif; max-width: 40rem; margin: 3rem auto;">
<h1>URL Shortener</h1>
<p>Generated by the agentic SDLC orchestrator.
<a href="/docs">Interactive API docs</a> &middot; <a href="/redoc">API reference</a></p>
<table style="border-collapse: collapse; width: 100%;">
<thead><tr>
<th style="text-align:left;">Method</th><th style="text-align:left;">Path</th>
</tr></thead>
<tbody>{rows}</tbody>
</table>
</body>
</html>"""
    return HTMLResponse(html)


app.include_router(router)
